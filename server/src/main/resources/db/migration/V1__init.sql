-- 로그인 도입 이전 스키마 (기존 db/init/01-schema.sql + 03-settings.sql).
-- 이미 이 스키마로 운영 중인 DB는 Flyway baseline(V1) 으로 처리되어 이 파일을 건너뛴다.

CREATE TABLE books (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(500) NOT NULL,
    author      VARCHAR(500),
    publisher   VARCHAR(500),
    isbn        VARCHAR(20),
    cover_url   TEXT,
    description TEXT,
    status      VARCHAR(20)  NOT NULL DEFAULT 'TO_READ'
                CHECK (status IN ('TO_READ', 'READING', 'FINISHED')),
    created_at  TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE TABLE cards (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id       BIGINT    NOT NULL REFERENCES books (id) ON DELETE CASCADE,
    image_url     TEXT,
    original_text TEXT,
    content       TEXT      NOT NULL DEFAULT '',
    highlights    JSONB,
    page_number   INTEGER,
    order_index   INTEGER   NOT NULL DEFAULT 0,
    created_at    TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    updated_at    TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE INDEX idx_cards_book_order ON cards (book_id, order_index);

CREATE TABLE app_settings (
    id                 INTEGER PRIMARY KEY CHECK (id = 1),
    current_book_id    BIGINT REFERENCES books (id) ON DELETE SET NULL,
    quick_card_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    quick_card_token   VARCHAR(64)
);

