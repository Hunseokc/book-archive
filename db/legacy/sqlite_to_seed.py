"""기존 FastAPI 백엔드의 SQLite(book_archive.db) 데이터를 Postgres 시드 SQL로 변환한다.

기존 Python(FastAPI) 백엔드는 삭제됐고, 변환 결과인 sqlite-seed.sql 만 남아 있다.

사용법:
  python db/legacy/sqlite_to_seed.py <book_archive.db 경로> db/legacy/sqlite-seed.sql
  # 새 DB라면 server 를 한 번 띄워 Flyway 가 테이블을 만든 뒤 넣는다.
  docker compose exec -T db psql -U book -d book_archive < db/legacy/sqlite-seed.sql
들어간 책은 소유자가 없고(user_id NULL), 첫 번째로 가입한 사용자에게 넘어간다.
"""

import sqlite3
import sys


def literal(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def dump(conn: sqlite3.Connection, table: str, columns: list[str], casts: dict[str, str]) -> list[str]:
    rows = conn.execute(f"SELECT {', '.join(columns)} FROM {table} ORDER BY id").fetchall()
    lines = []
    for row in rows:
        values = [literal(v) + casts.get(col, "") for col, v in zip(columns, row)]
        lines.append(f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({', '.join(values)});")
    # 명시적 id 로 넣었으므로 IDENTITY 시퀀스를 최대 id 이후로 맞춘다.
    lines.append(
        f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), COALESCE((SELECT MAX(id) FROM {table}), 0) + 1, false);"
    )
    return lines


def main(src: str, dst: str) -> None:
    conn = sqlite3.connect(src)
    lines = ["-- generated by db/sqlite_to_seed.py", "BEGIN;"]
    lines += dump(
        conn,
        "books",
        ["id", "title", "author", "publisher", "isbn", "cover_url", "description", "status", "created_at"],
        {},
    )
    lines += dump(
        conn,
        "cards",
        ["id", "book_id", "image_url", "original_text", "content", "highlights",
         "page_number", "order_index", "created_at", "updated_at"],
        {"highlights": "::jsonb"},
    )
    lines.append("COMMIT;")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
